def build_flow(
    encoder_output_size: int = 512,
    encoder_linear_units: int = 2048,
    encoder_num_blocks: int = 6,
    encoder_num_up_blocks: int = 4,
    encoder_attention_heads: int = 8,
    estimator_channels: int = 256,
    estimator_n_blocks: int = 4,
    estimator_num_mid_blocks: int = 12,
    estimator_num_heads: int = 8,
    estimator_attention_head_dim: int = 64,
) -> CausalMaskedDiffWithXvec:
    """Build a meanflow S3Gen flow.  Defaults reproduce the released architecture.

    Halving every width argument yields the pruned student.  The mel dimension
    (80) and the x-vector dimension (192) are interfaces to frozen components and
    stay fixed.

    ``estimator_channels`` takes an int for the released single-stage shape, or a
    list for a genuinely hierarchical UNet: every entry past the first adds a
    stride-2 stage, so the mid blocks then run at a fraction of the mel rate.
    That is the single biggest CPU lever, since mid-block attention is quadratic
    in sequence length.
    """
    encoder = UpsampleConformerEncoder(
        input_size=encoder_output_size,
        output_size=encoder_output_size,
        attention_heads=encoder_attention_heads,
        linear_units=encoder_linear_units,
        num_blocks=encoder_num_blocks,
        num_up_blocks=encoder_num_up_blocks,
        dropout_rate=0.1,
        positional_dropout_rate=0.1,
        attention_dropout_rate=0.1,
        normalize_before=True,
        input_layer="linear",
        pos_enc_layer_type="rel_pos_espnet",
        selfattention_layer_type="rel_selfattn",
        use_cnn_module=False,
        macaron_style=False,
    )
    est_channels = (
        [estimator_channels] if isinstance(estimator_channels, int)
        else list(estimator_channels)
    )
    estimator = ConditionalDecoder(
        in_channels=4 * N_MELS,
        out_channels=N_MELS,
        causal=True,
        channels=est_channels,
        dropout=0.0,
        attention_head_dim=estimator_attention_head_dim,
        n_blocks=estimator_n_blocks,
        num_mid_blocks=estimator_num_mid_blocks,
        num_heads=estimator_num_heads,
        act_fn="gelu",
        meanflow=True,
    )
    decoder = CausalConditionalCFM(
        spk_emb_dim=N_MELS, cfm_params=CFM_PARAMS, estimator=estimator
    )
    return CausalMaskedDiffWithXvec(
        input_size=encoder_output_size, encoder=encoder, decoder=decoder
    )


def meanflow_forward(
    flow: CausalMaskedDiffWithXvec,
    token,
    token_len,
    prompt_token,
    prompt_token_len,
    prompt_feat,
    embedding,
    z=None,
    n_steps: int = 1,
):
    """Run ``flow`` from noise to mel with ``n_steps`` meanflow Euler steps.

    Mirrors ``CausalMaskedDiffWithXvec.inference`` with ``finalize=True``, minus
    the ``inference_mode`` decorator, so gradients reach the student's weights.
    Classifier-free guidance is skipped, matching ``basic_euler``: the meanflow
    weights are trained without it.

    Args:
        z: starting noise over prompt *and* speech frames,
           ``[B, 80, 2 * (prompt_tokens + tokens)]``.  Drawn internally when
           ``None``, which is how the teacher creates the noise it then hands to
           the student.

    Returns:
        ``(mel, mask, z)`` — mel ``[B, 80, T_speech]`` and its validity mask
        ``[B, 80, T_speech]``, both already stripped of the prompt region, plus
        the noise actually integrated.
    """
    B = token.size(0)

    embedding = F.normalize(torch.atleast_2d(embedding), dim=1)
    embedding = flow.spk_embed_affine_layer(embedding)

    token = torch.cat([prompt_token, token], dim=1)
    token_len = prompt_token_len + token_len
    token_mask = (~make_pad_mask(token_len)).unsqueeze(-1).to(embedding)
    token = flow.input_embedding(token.long()) * token_mask

    h, h_masks = flow.encoder(token, token_len)
    h_lengths = h_masks.sum(dim=-1).squeeze(dim=-1)
    mel_len1 = prompt_feat.shape[1]
    h = flow.encoder_proj(h)

    conds = torch.zeros(B, h.shape[1], flow.output_size, device=h.device, dtype=h.dtype)
    conds[:, :mel_len1] = prompt_feat
    conds = conds.transpose(1, 2)

    mask = (~make_pad_mask(h_lengths)).unsqueeze(1).to(h)
    if mask.shape[0] != B:
        mask = mask.repeat(B, 1, 1)

    mu = h.transpose(1, 2).contiguous()
    if z is None:
        z = torch.randn_like(mu)  # encoder_proj makes mu [B, 80, T], same shape as x
    x = z.to(dtype=mu.dtype)

    estimator = flow.decoder.estimator
    t_span = torch.linspace(0, 1, n_steps + 1, device=mu.device, dtype=mu.dtype)
    for t, r in zip(t_span[:-1], t_span[1:]):
        dxdt = estimator(
            x, mask=mask, mu=mu, t=t[None], spks=embedding, cond=conds, r=r[None]
        )
        x = x + (r - t) * dxdt

    mel = x[:, :, mel_len1:]
    mel_mask = mask[:, :, mel_len1:].expand(-1, N_MELS, -1)
    return mel, mel_mask, z
