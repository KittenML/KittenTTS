"""The optional quantised decoder: a distilled student flow, tokens -> mel.

KittenTTS 2 decodes in two stages — a flow turns codec tokens into a mel
spectrogram, then a vocoder turns that into audio. This module is an alternative
first stage: a distilled student that runs in a single step with its weights
packed to 4 or 8 bits, cutting the flow from roughly 115 MB to 37 MB. The
tokenizer, speaker encoder and vocoder are untouched and still come from
`s3gen.py`.

The trade is deliberate and worth stating plainly: quantisation shrinks storage
and memory bandwidth, not arithmetic, so this is **not faster** without a kernel
that multiplies in low precision. Quality is also below the default decoder
(measured mel L1 against the teacher: 0.250 versus 0.168 for the dense student),
and voices far from the student's 539-speaker training pool degrade more than the
default decoder's would. Choose it for footprint, not for speed or fidelity.

Weights are loaded pre-quantised. Dequantising and re-quantising a weight is not a
no-op in floating point — rounding at a boundary shifts about 10% of weights by
~1e-7, which accumulated over 474 layers moved the mel output by 0.365. The stored
codes are therefore used directly.

Generated by scripts/vendor_student_flow.py; edit that, not this. Derived from
ResembleAI's chatterbox (Apache 2.0), which builds on Alibaba's CosyVoice and
Matcha-TTS, plus the BitNet-style quantised layers.
"""

