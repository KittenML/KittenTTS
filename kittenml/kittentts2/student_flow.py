def simple_rms_norm(x: Tensor, dim: int) -> Tensor:
    """L2-normalise over the last axis and scale by ``dim ** -0.5``."""
    return F.normalize(x, dim=-1) * (dim ** -0.5)


class SimpleRMSNorm(nn.Module):
    """Parameter-free. Kept as a module for API compatibility with zeta."""

    def __init__(self, dim: int):
        super().__init__()
        self.dim = dim
        self.scale = dim ** -0.5

    def forward(self, x: Tensor) -> Tensor:
        return F.normalize(x, dim=-1) * self.scale


def activation_quant(x: Tensor, eps: float = 1e-5) -> Tensor:
    """8-bit per-token quantisation. Scale is divided back out, so this is
    near-identity in magnitude and only the precision changes."""
    scale = 127.0 / x.abs().amax(dim=-1, keepdim=True).clamp(min=eps)
    return (x * scale).round().clamp(-128, 127) / scale


def weight_quant_ternary(w: Tensor, eps: float = 1e-5) -> Tensor:
    """BitNet b1.58: three levels, {-s, 0, +s} with s = mean|w|."""
    scale = 1.0 / w.abs().mean().clamp(min=eps)
    return (w * scale).round().clamp(-1, 1) / scale


def weight_quant_sign(w: Tensor) -> Tensor:
    """BitNet 1-bit: two levels. Binary despite often being called ternary."""
    scale = w.abs().mean()
    return (w - w.mean()).sign() * scale


def weight_quant_nbit(w: Tensor, bits: int, per_channel: bool = True,
                      group_size: int = 0, eps: float = 1e-5) -> Tensor:
    """Uniform signed n-bit weight quantisation.

    Per-channel by default: one scale per output channel rather than one for the
    whole tensor. At 8 bits the difference is small, but at 4 bits a single
    outlier channel otherwise sets the scale for every weight and most of the
    range goes unused. This is the standard choice for 4-bit PTQ.
    """
    qmax = float(2 ** (bits - 1) - 1)
    if group_size:
        # One scale per contiguous run of `group_size` weights within an output
        # channel. Standard for 4-bit LLM quantisation (GPTQ, AWQ use 128) and
        # much finer than per-channel, which for a conv covers in_ch * kernel
        # weights under a single scale.
        shape = w.shape
        flat = w.reshape(shape[0], -1)
        n = flat.shape[1]
        pad = (-n) % group_size
        if pad:
            flat = torch.nn.functional.pad(flat, (0, pad))
        g = flat.reshape(-1, group_size)
        scale = qmax / g.abs().amax(dim=1, keepdim=True).clamp(min=eps)
        q = (g * scale).round().clamp(-qmax - 1, qmax) / scale
        q = q.reshape(shape[0], -1)[:, :n]
        return q.reshape(shape)
    if per_channel:
        flat = w.reshape(w.shape[0], -1)
        scale = qmax / flat.abs().amax(dim=1).clamp(min=eps)
        scale = scale.reshape(-1, *([1] * (w.dim() - 1)))
    else:
        scale = qmax / w.abs().amax().clamp(min=eps)
    return (w * scale).round().clamp(-qmax - 1, qmax) / scale


_WEIGHT_QUANT = {"ternary": weight_quant_ternary, "sign": weight_quant_sign}


_NBIT_RE = re.compile(r"^w(\d+)(_pt)?(?:g(\d+))?(a16)?$")


def _check_mode(mode: str) -> str:
    """Modes: ``ternary``, ``sign``, or ``w<bits>`` (``w4``, ``w8``).

    A ``_pt`` suffix asks for per-tensor scaling instead of per-channel, which is
    only useful for showing why per-channel is the default.
    """
    if mode in _WEIGHT_QUANT or _NBIT_RE.match(mode):
        return mode
    raise ValueError(f"unknown quantise mode {mode!r}")


def _quantise_weight(w: Tensor, mode: str) -> Tensor:
    if mode in _WEIGHT_QUANT:
        return _WEIGHT_QUANT[mode](w)
    m = _NBIT_RE.match(mode)
    return weight_quant_nbit(w, int(m.group(1)), per_channel=m.group(2) is None,
                             group_size=int(m.group(3)) if m.group(3) else 0)


def _quantise_acts(mode: str) -> bool:
    """False for an ``a16`` mode, which leaves activations in full precision."""
    m = _NBIT_RE.match(mode)
    return not (m and m.group(4))


def _ste(x: Tensor, quantised: Tensor) -> Tensor:
    """Forward the quantised value, backprop as if it were the identity."""
    return x + (quantised - x).detach()


class BitLinear(nn.Linear):
    """``nn.Linear`` with quantised weights and 8-bit activations."""

    def __init__(self, in_features, out_features, bias=True,
                 mode: str = "ternary", norm_input: bool = True,
                 prequantised: bool = False, device=None, dtype=None):
        super().__init__(in_features, out_features, bias, device=device, dtype=dtype)
        self.mode = _check_mode(mode)
        self.norm_input = norm_input
        # Set when the stored weight is already on the quantisation grid, as in an
        # exported model. Re-quantising it is *not* a no-op in floating point:
        # dequantise-then-requantise flips ~10 % of weights by ~1e-7, which is
        # enough to move the output noticeably once it accumulates over 474 layers.
        self.prequantised = prequantised

    def forward(self, x: Tensor, scale: float = 1.0) -> Tensor:
        # `scale` exists only so this is a drop-in for diffusers'
        # LoRACompatibleLinear, which some call sites pass it to. There is no LoRA
        # here, so anything other than 1.0 would be silently dropped — refuse instead.
        if scale != 1.0:
            raise ValueError(f"BitLinear got scale={scale}; LoRA is not supported")
        x = simple_rms_norm(x, self.in_features) if self.norm_input else x
        x_q = _ste(x, activation_quant(x)) if _quantise_acts(self.mode) else x
        w_q = (self.weight if self.prequantised else
               _ste(self.weight, _quantise_weight(self.weight, self.mode)))
        return F.linear(x_q, w_q, self.bias)

    def extra_repr(self) -> str:
        return f"{super().extra_repr()}, mode={self.mode}"


class BitConv1d(nn.Conv1d):
    """``nn.Conv1d`` with quantised weights and 8-bit activations.

    Input is ``[B, C, T]``; the norm and the activation quantiser both act over the
    channel axis, so the tensor is transposed around them.
    """

    def __init__(self, in_channels, out_channels, kernel_size, stride=1, padding=0,
                 dilation=1, groups=1, bias=True, padding_mode="zeros",
                 mode: str = "ternary", norm_input: bool = True,
                 causal_padding=None, prequantised: bool = False,
                 device=None, dtype=None):
        super().__init__(in_channels, out_channels, kernel_size, stride, padding,
                         dilation, groups, bias, padding_mode,
                         device=device, dtype=dtype)
        self.mode = _check_mode(mode)
        self.norm_input = norm_input
        self.prequantised = prequantised     # see BitLinear
        # Carried over from CausalConv1d, which pads in its forward rather than
        # through nn.Conv1d's padding argument. Dropping it silently shortens the
        # sequence and the model stops assembling.
        self.causal_padding = tuple(causal_padding) if causal_padding else None

    def forward(self, x: Tensor) -> Tensor:
        if self.causal_padding:
            x = F.pad(x, self.causal_padding)
        xt = x.transpose(-1, -2)
        if self.norm_input:
            xt = simple_rms_norm(xt, self.in_channels)
        xq = _ste(xt, activation_quant(xt)) if _quantise_acts(self.mode) else xt
        x_q = xq.transpose(-1, -2)
        w_q = (self.weight if self.prequantised else
               _ste(self.weight, _quantise_weight(self.weight, self.mode)))
        return self._conv_forward(x_q, w_q, self.bias)

    def extra_repr(self) -> str:
        return f"{super().extra_repr()}, mode={self.mode}"


DEFAULT_SKIP = ("final_proj", "input_embedding", "spk_embed_affine_layer")


def _is_plain_linear(m: nn.Module) -> bool:
    """An nn.Linear, or a subclass that behaves exactly like one right now.

    diffusers' LoRACompatibleLinear wraps every transformer feed-forward; with no
    LoRA attached its forward is plain F.linear, and it holds 6.9 M of the
    half-size flow's weights — too much to leave dense over a type check.
    """
    if type(m) is nn.Linear:
        return True
    return (isinstance(m, nn.Linear) and not isinstance(m, BitLinear)
            and type(m).__name__ == "LoRACompatibleLinear"
            and getattr(m, "lora_layer", None) is None)


def _is_causal_conv1d(m: nn.Module) -> bool:
    """A Conv1d subclass whose only extra behaviour is a causal pre-pad."""
    return (isinstance(m, nn.Conv1d) and not isinstance(m, BitConv1d)
            and type(m).__name__ == "CausalConv1d"
            and getattr(m, "causal_padding", None) is not None)


def convert_to_bitnet(module: nn.Module, mode: str = "ternary",
                      skip: tuple = DEFAULT_SKIP, norm_input: bool = True,
                      prequantised: bool = False, _prefix: str = "") -> nn.Module:
    """Replace every ``nn.Linear`` / ``nn.Conv1d`` in ``module``, in place.

    Args:
        module: model to convert.
        mode: ``ternary`` or ``sign``.
        skip: names matched against the dotted path of each layer; a layer whose
            path contains any of these substrings is left dense.
        norm_input: apply SimpleRMSNorm to layer inputs, as BitNet specifies.

    Returns the same module, converted.
    """
    for name, child in list(module.named_children()):
        path = f"{_prefix}{name}"
        if any(s in path for s in skip):
            continue
        # Exact type only. Subclasses (CausalConv1d, the tokenizer's _S3Linear /
        # _S3Conv1d) override forward, and replacing them would throw that away.
        # CausalConv1d is handled explicitly below.
        if _is_plain_linear(child):
            new = BitLinear(child.in_features, child.out_features,
                            bias=child.bias is not None, mode=mode,
                            norm_input=norm_input, prequantised=prequantised)
            new.weight.data.copy_(child.weight.data)
            if child.bias is not None:
                new.bias.data.copy_(child.bias.data)
            setattr(module, name, new)
        elif type(child) is nn.Conv1d or _is_causal_conv1d(child):
            new = BitConv1d(child.in_channels, child.out_channels, child.kernel_size,
                            stride=child.stride, padding=child.padding,
                            dilation=child.dilation, groups=child.groups,
                            bias=child.bias is not None,
                            padding_mode=child.padding_mode, mode=mode,
                            norm_input=norm_input, prequantised=prequantised,
                            causal_padding=getattr(child, "causal_padding", None))
            new.weight.data.copy_(child.weight.data)
            if child.bias is not None:
                new.bias.data.copy_(child.bias.data)
            setattr(module, name, new)
        else:
            convert_to_bitnet(child, mode=mode, skip=skip, norm_input=norm_input,
                              prequantised=prequantised, _prefix=f"{path}.")
    return module


def count_quantised(module: nn.Module) -> dict:
    """Parameters that end up quantised versus left dense, and the memory that buys."""
    q = sum(m.weight.numel() for m in module.modules()
            if isinstance(m, (BitLinear, BitConv1d)))
    total = sum(p.numel() for p in module.parameters())
    # ternary needs log2(3) bits per weight; everything else stays fp16
    bits = q * 1.58 + (total - q) * 16
    return dict(total=total, quantised=q, dense=total - q,
                quantised_frac=q / total if total else 0.0,
                mb_fp16=total * 16 / 8 / 2**20, mb_ternary=bits / 8 / 2**20)


